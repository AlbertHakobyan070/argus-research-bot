"""Import a Noetrix theme export as console themes.

    ./venv/Scripts/python.exe scripts/import_noetrix_themes.py <noetrix-themes-*.json>

Writes ``src/argus/webapp/static/themes-noetrix.css`` (a ``:root[data-theme=…]``
block and a swatch per theme, in the kit's token names) and
``themes-noetrix.json`` (id, name, mode: read by ``webapp/api.py`` and the
Settings view). Noetrix tokens map onto the kit's; the ones Noetrix does not
carry (shadows, chart colours c1–c8) come from the kit's own light or dark
theme for the theme's mode. An invalid colour or a clash with a kit theme id
fails the import, naming the theme and token.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

STATIC = Path(__file__).resolve().parents[1] / "src" / "argus" / "webapp" / "static"
KIT_TOKENS = STATIC / "vendor" / "arsenal" / "tokens" / "tokens.css"
KIT_IDS = {"system", "light", "ledger", "dark", "steel", "graphite", "solar", "slate", "paper", "contrast"}
KIT_BASE = {"light": "ledger", "dark": "dark"}            # the kit theme a mode borrows the rest from
FROM_KIT = ("shadow", "pop-shadow", *(f"c{i}" for i in range(1, 9)))
_COLOR = re.compile(r"#[0-9a-fA-F]{6}|rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*(,\s*[\d.]+\s*)?\)")


def _rgba(hex_color: str, alpha: float) -> str:
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r},{g},{b},{alpha})"


def _kit_block(theme: str) -> dict[str, str]:
    css = KIT_TOKENS.read_text(encoding="utf-8")
    m = re.search(r':root\[data-theme="' + theme + r'"\][^{]*\{([^}]*)\}', css)
    if m is None:
        raise ValueError(f"kit theme {theme!r} not found in {KIT_TOKENS}")
    return dict(re.findall(r"--([\w-]+):\s*([^;]+);", m.group(1)))


def tokens(theme_id: str, nx: dict[str, str], mode: str) -> dict[str, str]:
    for name, value in nx.items():
        if not _COLOR.fullmatch(value.strip()):
            raise ValueError(f"theme {theme_id!r}: --{name} is not a colour ({value!r})")
    accent = nx["amber"]
    if not accent.startswith("#"):
        raise ValueError(f"theme {theme_id!r}: --amber must be a #rrggbb colour ({accent!r})")
    kit = _kit_block(KIT_BASE[mode])
    return {
        "ground": nx["bg"], "panel": nx["panel"], "panel-2": nx["panel-2"], "sunk": nx["log-bg"],
        "line": nx["line"], "line-soft": nx["td-line"],
        "ink": nx["ink"], "ink-dim": nx["ink-dim"], "ink-faint": nx["ink-faint"],
        "accent": accent, "accent-soft": _rgba(accent, .10), "accent-line": _rgba(accent, .34),
        "why": accent, "trap": nx["red"], "mech": nx["blue"], "cost": nx["green"],
        "code-bg": nx["log-bg"], "code-line": nx["line"],
        "sel": nx["row-sel"], "mark": _rgba(accent, .28), "on-fill": nx["btn-primary-ink"],
        **{k: kit[k] for k in FROM_KIT},
    }


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    data = json.loads(Path(argv[0]).read_text(encoding="utf-8"))
    if data.get("format") != "noetrix-themes":
        raise ValueError(f"not a Noetrix theme export (format {data.get('format')!r})")
    css, listing = ["/* Generated by scripts/import_noetrix_themes.py — do not edit by hand. */"], []
    for theme_id, t in data["themes"].items():
        if theme_id in KIT_IDS or not re.fullmatch(r"[a-z0-9-]+", theme_id):
            raise ValueError(f"theme id {theme_id!r} clashes with a kit theme or is not a plain slug")
        mode = t["mode"]
        if mode not in KIT_BASE:
            raise ValueError(f"theme {theme_id!r}: mode must be light or dark ({mode!r})")
        nx = dict(re.findall(r"--([\w-]+):\s*([^;]+);", t["css"]))
        tok = tokens(theme_id, nx, mode)
        body = "\n".join(f"  --{k}: {v.strip()};" for k, v in tok.items())
        css.append(f':root[data-theme="{theme_id}"] {{\n{body}\n  color-scheme: {mode};\n}}')
        css.append(f'.tsw[data-theme-id="{theme_id}"]{{--a:{tok["ground"]};--b:{tok["accent"]}}}')
        label = t.get("label") or theme_id
        name = label.replace("-", " ").title() if label == theme_id else label
        listing.append({"id": theme_id, "name": name, "mode": mode})
    (STATIC / "themes-noetrix.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    (STATIC / "themes-noetrix.json").write_text(json.dumps(listing, indent=1) + "\n", encoding="utf-8")
    print(f"{len(listing)} themes: " + ", ".join(f"{x['name']} ({x['mode']})" for x in listing))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
