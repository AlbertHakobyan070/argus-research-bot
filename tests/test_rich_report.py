async def test_a_rich_report_still_flooded_after_its_retry_is_not_called_refused(env, monkeypatch):
    monkeypatch.setattr(tgx, "_sleep", AsyncMock())
    run_id = await _at_report_gate(env)
    env.bot.do_api_request = AsyncMock(side_effect=RetryAfter(5))
    assert (await runs.report_action(run_id, "send")).code == "delivered"
    sent = _sent(env)
    assert len(_rich_calls(env)) == 2 and tgx._sleep.await_args.args == (5,)
    assert ("⚠️ The rich report message could not be sent (RetryAfter: Flood control exceeded. Retry in 5 seconds), "
            "so the report comes as files only.") in sent and not [t for t in sent if "refused" in t]
    assert env.bot.send_document.await_count == 1 and "✅ Delivered." in sent


